import { describe, expect, it } from "vitest";
import { hoursRange, ofLessons, plural } from "./ru";

describe("русские формы", () => {
  it("склоняет «урок» при числе", () => {
    expect([1, 2, 5, 11, 12, 21, 22, 54, 111].map((n) => plural(n, "урок", "урока", "уроков"))).toEqual([
      "урок", "урока", "уроков", "уроков", "уроков", "урок", "урока", "урока", "уроков",
    ]);
  });
  it("после «из» — родительный падеж", () => {
    expect([1, 7, 11, 21, 52].map(ofLessons)).toEqual(["урока", "уроков", "уроков", "урока", "уроков"]);
  });
  it("пишет диапазон часов с неразрывным пробелом", () => {
    expect(hoursRange([12, 15])).toBe("12–15\u00a0часов");
    expect(hoursRange([4, 4])).toBe("4\u00a0часа");
  });
});
