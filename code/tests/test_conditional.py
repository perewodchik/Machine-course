"""Числа урока III.2: броски одной из двух монет зависимы (0.7 против 0.757), но независимы при известной монете."""

from prob.conditional import _lesson_cell


def test_lesson_cell_output(capsys):
    """Ячейка урока III.2 (<PyCode src="prob/conditional.py#demo" run />) печатает ровно это.

    Точные значения: P(орёл₂) = ½·0.9 + ½·0.5 = 0.7, P(орёл₂ | орёл₁) = (½·0.81 + ½·0.25) / 0.7 ≈ 0.757.
    """
    _lesson_cell()
    assert capsys.readouterr().out == (
        "P(орёл₂)            ≈ 0.698\n"
        "P(орёл₂ | орёл₁)    ≈ 0.756\n"
        "монета кривая: P(орёл₂ | C) ≈ 0.899, P(орёл₂ | орёл₁, C) ≈ 0.898\n"
        "монета честная: P(орёл₂ | C) ≈ 0.498, P(орёл₂ | орёл₁, C) ≈ 0.498\n"
    )
